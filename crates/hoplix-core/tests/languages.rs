use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use hoplix_core::language::{
    self, CATEGORIES, DIRECTION_KEY, ENGLISH_CODE, FALLBACK_KEY, FILE_EXTENSION, LanguageFile,
    NAME_KEY,
};

// Constants

const DOCUMENT: &str = "LANGUAGES.md";
const UPDATE_VARIABLE: &str = "UPDATE_LANGUAGES";
const AI_NOTICE: &str = "# Generated by Claude (AI)";
const REPORT_LINK: &str = "https://github.com/TripleT3005/Hoplix/issues";

// Helpers

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn language_texts() -> Vec<(String, String)> {
    let mut texts: Vec<_> = fs::read_dir(root().join("lang"))
        .expect("reading the lang folder failed")
        .map(|item| item.expect("reading an entry failed").path())
        .filter(|path| path.extension().and_then(|e| e.to_str()) == Some(FILE_EXTENSION))
        .map(|path| {
            let code = path
                .file_stem()
                .and_then(|stem| stem.to_str())
                .expect("language file names are UTF-8")
                .to_string();
            let text = fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("reading {} failed: {error}", path.display()));
            (code, text)
        })
        .collect();
    texts.sort();
    assert!(!texts.is_empty(), "the lang folder has no language files");
    texts
}

fn languages() -> Vec<LanguageFile> {
    language_texts()
        .iter()
        .map(|(code, text)| LanguageFile::parse(code, text))
        .collect()
}

fn english() -> LanguageFile {
    languages()
        .into_iter()
        .find(|language| language.code == ENGLISH_CODE)
        .expect("lang/en.lang is missing")
}

fn placeholders(text: &str) -> BTreeSet<&str> {
    text.split('{')
        .skip(1)
        .filter_map(|part| part.split_once('}'))
        .map(|(name, _)| name)
        .collect()
}

// Tests

#[test]
fn every_language_file_has_a_header() {
    for (code, text) in language_texts() {
        let language = LanguageFile::parse(&code, &text);
        let title = language.title.as_deref().unwrap_or_default();
        assert!(
            title.ends_with(&format!("({code})")),
            "{code}: the title line must end with ({code})"
        );
        assert!(
            CATEGORIES
                .iter()
                .any(|(category, _)| *category == language.category),
            "{code}: unknown category {}",
            language.category
        );
        assert!(text.contains(AI_NOTICE), "{code}: the AI notice is missing");
        assert!(
            text.contains(REPORT_LINK),
            "{code}: the report link is missing"
        );
        assert!(
            text.lines()
                .any(|line| line.starts_with(language::REVIEWED_BY_PREFIX.trim_end())),
            "{code}: the Reviewed by line is missing"
        );
        assert!(language.get(NAME_KEY).is_some(), "{code}: {NAME_KEY}");
    }
}

#[test]
fn language_files_only_use_known_keys() {
    let english = english();
    for language in languages() {
        let unknown: Vec<_> = language
            .entries
            .keys()
            .filter(|key| {
                !english.entries.contains_key(*key)
                    && key.as_str() != FALLBACK_KEY
                    && key.as_str() != DIRECTION_KEY
            })
            .collect();
        assert!(unknown.is_empty(), "{}: {unknown:?}", language.code);
    }
}

#[test]
fn backslashes_are_escaped() {
    for (code, text) in language_texts() {
        for (number, line) in text.lines().enumerate() {
            if line.starts_with('#') {
                continue;
            }
            let mut chars = line.chars();
            while let Some(c) = chars.next() {
                if c == '\\' {
                    assert!(
                        matches!(chars.next(), Some('n' | '\\')),
                        "{code}.lang line {}: write a backslash as \\\\ and a line break as \\n",
                        number + 1
                    );
                }
            }
        }
    }
}

#[test]
fn placeholders_match_english() {
    let english = english();
    for language in languages() {
        for (key, value) in &language.entries {
            if let Some(original) = english.entries.get(key) {
                assert_eq!(
                    placeholders(value),
                    placeholders(original),
                    "{}: {key}",
                    language.code
                );
            }
        }
    }
}

#[test]
fn languages_document_is_up_to_date() {
    let expected = language::languages_document(&languages());
    let path = root().join(DOCUMENT);
    if env::var(UPDATE_VARIABLE).is_ok_and(|value| value == "1") {
        fs::write(&path, &expected).expect("writing LANGUAGES.md failed");
    }
    let actual = fs::read_to_string(&path)
        .unwrap_or_else(|_| {
            panic!("{DOCUMENT} is missing. Run the tests with {UPDATE_VARIABLE}=1.")
        })
        .replace("\r\n", "\n");
    assert!(
        actual == expected,
        "{DOCUMENT} is outdated. Run the tests with {UPDATE_VARIABLE}=1."
    );
}
