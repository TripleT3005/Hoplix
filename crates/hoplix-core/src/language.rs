use std::collections::HashMap;
use std::fmt::Write;

use crate::key_value;

// Constants

pub const ENGLISH_CODE: &str = "en";
pub const FILE_EXTENSION: &str = "lang";
pub const NAME_KEY: &str = "language.name";
pub const FALLBACK_KEY: &str = "language.fallback";
pub const DIRECTION_KEY: &str = "language.direction";
pub const STANDARD_CATEGORY: &str = "standard";
pub const TITLE_PREFIX: &str = "# Hoplix language file: ";
pub const CATEGORY_PREFIX: &str = "# Category: ";
pub const REVIEWED_BY_PREFIX: &str = "# Reviewed by: ";
pub const CATEGORIES: [(&str, &str); 3] = [
    (STANDARD_CATEGORY, "Standard languages / Standardsprachen"),
    ("dialect", "Dialects / Dialekte"),
    ("fun", "Fun languages / Spaßsprachen"),
];
const ISSUES_URL: &str = "https://github.com/TripleT3005/Hoplix/issues";
const RIGHT_TO_LEFT: &str = "rtl";
const NO_REVIEWER: &str = "-";

// Types

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Direction {
    #[default]
    LeftToRight,
    RightToLeft,
}

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct LanguageFile {
    pub code: String,
    pub title: Option<String>,
    pub category: String,
    pub reviewers: Vec<String>,
    pub entries: HashMap<String, String>,
}

// Parsing

impl LanguageFile {
    pub fn parse(code: &str, text: &str) -> Self {
        let mut file = Self {
            code: code.to_string(),
            category: STANDARD_CATEGORY.to_string(),
            entries: key_value::parse(text).into_iter().collect(),
            ..Self::default()
        };
        for line in text.trim_start_matches('\u{feff}').lines() {
            let line = line.trim();
            if let Some(title) = line.strip_prefix(TITLE_PREFIX) {
                file.title = Some(title.trim().to_string());
            } else if let Some(category) = line.strip_prefix(CATEGORY_PREFIX) {
                category.trim().clone_into(&mut file.category);
            } else if let Some(reviewers) = line.strip_prefix(REVIEWED_BY_PREFIX) {
                file.reviewers.extend(
                    reviewers
                        .split(',')
                        .map(str::trim)
                        .filter(|reviewer| !reviewer.is_empty() && *reviewer != NO_REVIEWER)
                        .map(|reviewer| reviewer.trim_start_matches('@').to_string()),
                );
            }
        }
        file
    }

    pub fn get(&self, key: &str) -> Option<&str> {
        self.entries.get(key).map(String::as_str)
    }

    pub fn name(&self) -> &str {
        self.get(NAME_KEY).unwrap_or(&self.code)
    }

    pub fn english_name(&self) -> &str {
        self.title
            .as_deref()
            .and_then(|title| title.strip_suffix(&format!("({})", self.code)))
            .map_or_else(|| self.name(), str::trim)
    }

    pub fn fallback(&self) -> Option<&str> {
        self.get(FALLBACK_KEY).filter(|code| !code.is_empty())
    }

    pub fn direction(&self) -> Direction {
        match self.get(DIRECTION_KEY) {
            Some(value) if value.eq_ignore_ascii_case(RIGHT_TO_LEFT) => Direction::RightToLeft,
            _ => Direction::LeftToRight,
        }
    }
}

// Document

pub fn languages_document(languages: &[LanguageFile]) -> String {
    let mut sorted: Vec<&LanguageFile> = languages.iter().collect();
    sorted.sort_by(|left, right| left.code.cmp(&right.code));
    let mut document = format!(
        "# Languages

[English](#english) · [Deutsch](#deutsch)

## English

All translations were generated by Claude (AI). Files that a person has checked name the reviewer in the table and in the file itself. If you notice a mistake or know a better wording, please open an [issue]({ISSUES_URL}) or a pull request; reviewers are credited with their GitHub name if they agree.

The codes follow [BCP 47](https://www.rfc-editor.org/info/bcp47): ISO 639 language codes, ISO 3166 regions and ISO 15924 scripts. Dialects use their ISO 639-3 code where one exists, everything else a private-use code with `-x-`. Missing texts fall back one by one to the language named in the file, otherwise to English.

This list is generated from the headers of the files in [`lang`](lang). After changing them, run `UPDATE_LANGUAGES=1 cargo test -p hoplix-core --test languages` (PowerShell: `$env:UPDATE_LANGUAGES = 1; cargo test -p hoplix-core --test languages`) to update it; the CI fails if it is out of date.

## Deutsch

Alle Übersetzungen wurden von Claude (KI) erzeugt. Dateien, die eine Person geprüft hat, nennen die prüfende Person in der Tabelle und in der Datei selbst. Wenn dir ein Fehler auffällt oder du eine bessere Formulierung kennst, eröffne gern ein [Issue]({ISSUES_URL}) oder einen Pull Request; mit Einverständnis wird die prüfende Person mit ihrem GitHub-Namen genannt.

Die Codes folgen [BCP 47](https://www.rfc-editor.org/info/bcp47): ISO-639-Sprachcodes, ISO-3166-Regionen und ISO-15924-Schriften. Dialekte nutzen ihren ISO-639-3-Code, sofern es einen gibt, alles andere einen Private-Use-Code mit `-x-`. Fehlende Texte fallen einzeln auf die in der Datei genannte Sprache zurück, sonst auf Englisch.

Diese Liste wird aus den Köpfen der Dateien in [`lang`](lang) erzeugt. Nach Änderungen daran aktualisiert `UPDATE_LANGUAGES=1 cargo test -p hoplix-core --test languages` (PowerShell: `$env:UPDATE_LANGUAGES = 1; cargo test -p hoplix-core --test languages`) sie; die CI schlägt fehl, wenn sie veraltet ist.
"
    );
    for (category, heading) in CATEGORIES {
        let entries: Vec<_> = sorted
            .iter()
            .filter(|language| language.category.eq_ignore_ascii_case(category))
            .collect();
        if entries.is_empty() {
            continue;
        }
        let _ = write!(
            document,
            "\n## {heading}\n\n| Code | Language | Name in the language list | Reviewed by |\n|---|---|---|---|\n"
        );
        for language in entries {
            let reviewers = if language.reviewers.is_empty() {
                "–".to_string()
            } else {
                language
                    .reviewers
                    .iter()
                    .map(|reviewer| format!("[@{reviewer}](https://github.com/{reviewer})"))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let _ = writeln!(
                document,
                "| `{}` | {} | {} | {reviewers} |",
                language.code,
                language.english_name(),
                language.name()
            );
        }
    }
    document
}

#[cfg(test)]
mod tests {
    use super::*;

    // Parsing

    #[test]
    fn parses_header_entries_and_direction() {
        let file = LanguageFile::parse(
            "ar-x-test",
            "# Hoplix language file: Test Arabic (ar-x-test)\n# Category: fun\n# Reviewed by: @Someone, Other\nlanguage.name = Test\nlanguage.fallback = de\nlanguage.direction = RTL\nkey = a = b\n",
        );
        assert_eq!(file.title.as_deref(), Some("Test Arabic (ar-x-test)"));
        assert_eq!(file.english_name(), "Test Arabic");
        assert_eq!(file.name(), "Test");
        assert_eq!(file.category, "fun");
        assert_eq!(file.reviewers, ["Someone", "Other"]);
        assert_eq!(file.fallback(), Some("de"));
        assert_eq!(file.direction(), Direction::RightToLeft);
        assert_eq!(file.get("key"), Some("a = b"));
    }

    #[test]
    fn missing_header_uses_defaults() {
        let file = LanguageFile::parse("xx", "# Reviewed by: -\nlanguage.fallback =\n");
        assert_eq!(file.title, None);
        assert_eq!(file.english_name(), "xx");
        assert_eq!(file.category, STANDARD_CATEGORY);
        assert!(file.reviewers.is_empty());
        assert_eq!(file.fallback(), None);
        assert_eq!(file.direction(), Direction::LeftToRight);
    }

    // Document

    #[test]
    fn document_lists_languages_by_category_and_code() {
        let languages = [
            LanguageFile::parse(
                "fr",
                "# Hoplix language file: French (fr)\n# Reviewed by: @Reviewer\nlanguage.name = Français\n",
            ),
            LanguageFile::parse(
                "bar",
                "# Hoplix language file: Bavarian (bar)\n# Category: dialect\nlanguage.name = Boarisch\n",
            ),
            LanguageFile::parse(
                "de",
                "# Hoplix language file: German (de)\nlanguage.name = Deutsch\n",
            ),
        ];
        let document = languages_document(&languages);
        let german = document.find("| `de` | German | Deutsch | – |").unwrap();
        let french = document
            .find("| `fr` | French | Français | [@Reviewer](https://github.com/Reviewer) |")
            .unwrap();
        let dialects = document.find("## Dialects / Dialekte").unwrap();
        let bavarian = document
            .find("| `bar` | Bavarian | Boarisch | – |")
            .unwrap();
        assert!(german < french && french < dialects && dialects < bavarian);
        assert!(!document.contains("Fun languages"));
    }
}
